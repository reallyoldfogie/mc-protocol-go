			sb.WriteString("<tr>")
			sb.WriteString(fmt.Sprintf("<td>%s</td>", html.EscapeString(r.State)))
			sb.WriteString(fmt.Sprintf("<td>%s</td>", html.EscapeString(r.Direction)))

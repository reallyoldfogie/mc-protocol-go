// Structures matching the ground truth results bundle
type versionBlock struct {
	Version string                            `json:"version"`
	Results []packetlogtest.GroundTruthResult `json:"results"`
	Summary struct {
		Total   int `json:"total"`
		Success int `json:"success"`
		Failed  int `json:"failed"`
	} `json:"summary"`
}

func main() {
	var (
		testFile     string
		testPaths    string
		version      string
		configPath   string
		verbose      bool
		showSuccess  bool
		jsonOut      string
		htmlOut      string
		mdOut        string
		failOnErrors bool
	)

	flag.StringVar(&testFile, "test-file", "", "Path to ground truth test file (JSONL), supports shell globs (e.g., tests/*.jsonl)")
	flag.StringVar(&testPaths, "test-paths", "", "Comma-separated list of files or directories to search for .jsonl test files")
	flag.StringVar(&version, "version", "", "Minecraft version to test (if not specified, tests all versions from config)")
	flag.StringVar(&configPath, "config", "configs/config.yaml", "Path to configuration file (used when --version not specified)")
	flag.BoolVar(&verbose, "verbose", false, "Show detailed output")
	flag.BoolVar(&showSuccess, "show-success", false, "Show successful validations (default: only failures)")
	flag.StringVar(&jsonOut, "json", "", "Write JSON results to specified file (text output still goes to stdout)")
	flag.StringVar(&htmlOut, "html", "", "Write HTML report to specified file (derived from JSON bundle)")
	flag.StringVar(&mdOut, "md", "", "Write Markdown report to specified file (derived from JSON bundle)")
	flag.BoolVar(&failOnErrors, "fail-on-errors", false, "Exit with non-zero status if any validations fail")

	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: %s -test-file <path> [-version <version>]\n\n", os.Args[0])
		fmt.Fprintln(os.Stderr, "Validates Go packet parser against ground truth test cases generated by node-minecraft-protocol.")
		fmt.Fprintln(os.Stderr, "\nOptions:")
		flag.PrintDefaults()
		fmt.Fprintln(os.Stderr, "\nSupported versions:")
		fmt.Fprintln(os.Stderr, "  1.21.1, 1.21.2, 1.21.3, 1.21.4, 1.21.5, 1.21.6, 1.21.7, 1.21.8")
		fmt.Fprintln(os.Stderr, "\nExamples:")
		fmt.Fprintln(os.Stderr, "  # Test a specific version")
		fmt.Fprintln(os.Stderr, "  go run ./cmd/groundtruth-validation -test-file test.jsonl -version 1.21.5")
		fmt.Fprintln(os.Stderr, "\n  # Test all versions from config")
		fmt.Fprintln(os.Stderr, "  go run ./cmd/groundtruth-validation -test-file test.jsonl")
	}

	flag.Parse()

	if testFile == "" && testPaths == "" {
		fmt.Fprintln(os.Stderr, "Error: one of -test-file or -test-paths is required")
		flag.Usage()
		os.Exit(1)
	}

	// Resolve test files (support globs and directories)
	testFiles := []string{}
	if testFile != "" {
		// Expand glob if present
		if hasGlob(testFile) {
			matches, err := filepath.Glob(testFile)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Invalid glob for -test-file: %v\n", err)
				os.Exit(1)
			}
			testFiles = append(testFiles, matches...)
		} else {
			testFiles = append(testFiles, testFile)
		}
	}
	if testPaths != "" {
		paths := strings.Split(testPaths, ",")
		files, err := collectJSONLFiles(paths)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error collecting test files: %v\n", err)
			os.Exit(1)
		}
		testFiles = append(testFiles, files...)
	}
	// Deduplicate
	if len(testFiles) == 0 {
		fmt.Fprintln(os.Stderr, "No test files found (.jsonl)")
		os.Exit(1)
	}
	testFiles = uniqStrings(testFiles)

	// Determine which versions to test
	var versionsToTest []string
	if version != "" {
		// Single version specified
		versionsToTest = []string{version}
	} else {
		// Load all versions from config
		cfg, err := loadConfig(configPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error loading config: %v\n", err)
			os.Exit(1)
		}
		versionsToTest = cfg.Versions
		fmt.Printf("Testing all versions from config: %v\n\n", versionsToTest)
	}

	// JSON aggregation structures
	var jsonBundle struct {
		Versions []versionBlock `json:"versions"`
		Total    struct {
			Versions int `json:"versions"`
			Tests    int `json:"tests"`
			Success  int `json:"success"`
			Failed   int `json:"failed"`
		} `json:"total"`
	}

	// Run validation for each version
	totalSuccess := 0
	totalFail := 0
	hasFailures := false

	for _, ver := range versionsToTest {
		if len(versionsToTest) > 1 {
			fmt.Printf("=== Testing version %s ===\n", ver)
		}

		// Load packet manager for this version
		packetMgr := versions.GetPacketMgrForVersion(ver)

		// Run validation across all test files
		var results []packetlogtest.GroundTruthResult
		for _, tf := range testFiles {
			r, err := packetlogtest.ValidateGroundTruthForVersion(tf, packetMgr)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", tf, err)
				os.Exit(1)
			}
			results = append(results, r...)
		}

		// Display results
		successCount := 0
		failCount := 0

		for _, result := range results {
			if result.Success {
				successCount++
				if showSuccess {
					fmt.Printf("✓ %s (%s, ID=%d)\n", result.Description, result.PacketName, result.PacketID)
				}
			} else {
				failCount++
				fmt.Printf("✗ %s (%s, ID=%d)\n", result.Description, result.PacketName, result.PacketID)
				for _, err := range result.Errors {
					fmt.Printf("  - %s\n", err)
				}
			}
		}

		// Summary for this version
		fmt.Printf("\n")
		fmt.Printf("Summary for %s:\n", ver)
		total := len(results)
		successPct := 0.0
		failPct := 0.0
		if total > 0 {
			successPct = float64(successCount) / float64(total) * 100
			failPct = float64(failCount) / float64(total) * 100
		}
		fmt.Printf("  Total:   %d\n", total)
		fmt.Printf("  Success: %d (%.1f%%)\n", successCount, successPct)
		fmt.Printf("  Failed:  %d (%.1f%%)\n", failCount, failPct)
		fmt.Printf("\n")

		totalSuccess += successCount
		totalFail += failCount
		if failCount > 0 {
			hasFailures = true
		}

		// Add to JSON bundle
		vb := versionBlock{Version: ver, Results: results}
		vb.Summary.Total = len(results)
		vb.Summary.Success = successCount
		vb.Summary.Failed = failCount
		jsonBundle.Versions = append(jsonBundle.Versions, vb)
	}

	// Overall summary if testing multiple versions
	if len(versionsToTest) > 1 {
		fmt.Printf("=== Overall Summary ===\n")
		fmt.Printf("Versions tested: %d\n", len(versionsToTest))
		fmt.Printf("Total tests:     %d\n", totalSuccess+totalFail)
		fmt.Printf("Total success:   %d\n", totalSuccess)
		fmt.Printf("Total failed:    %d\n", totalFail)
	}

	// Finalize bundle totals once
	jsonBundle.Total.Versions = len(jsonBundle.Versions)
	jsonBundle.Total.Tests = totalSuccess + totalFail
	jsonBundle.Total.Success = totalSuccess
	jsonBundle.Total.Failed = totalFail

	// Sort versions for stable output (also affects report tables)
	sort.Slice(jsonBundle.Versions, func(i, j int) bool { return jsonBundle.Versions[i].Version < jsonBundle.Versions[j].Version })

	// Write JSON if requested
	if jsonOut != "" {
		if err := writeJSON(jsonOut, jsonBundle, verbose); err != nil {
			fmt.Fprintf(os.Stderr, "%v\n", err)
			os.Exit(1)
		}
	}

	// Render HTML/Markdown if requested using templates
	report := buildReportData(jsonBundle)
	if htmlOut != "" {
		out, err := renderHTMLTemplate(report)
		if err != nil {
			fmt.Fprintf(os.Stderr, "render html: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(htmlOut, []byte(out), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "write html: %v\n", err)
			os.Exit(1)
		}
		if verbose {
			fmt.Fprintf(os.Stderr, "HTML report written to %s\n", htmlOut)
		}
	}
	if mdOut != "" {
		out, err := renderMDTemplate(report)
		if err != nil {
			fmt.Fprintf(os.Stderr, "render markdown: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(mdOut, []byte(out), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "write markdown: %v\n", err)
			os.Exit(1)
		}
		if verbose {
			fmt.Fprintf(os.Stderr, "Markdown report written to %s\n", mdOut)
		}
	}

	// At end of summary, show links to generated reports if any
	if htmlOut != "" || mdOut != "" {
		fmt.Printf("Reports:\n")
		if htmlOut != "" {
			fmt.Printf("  HTML: %s\n", mustAbs(htmlOut))
		}
		if mdOut != "" {
			fmt.Printf("  Markdown: %s\n", mustAbs(mdOut))
		}
	}

	// Optionally fail the process when validations failed
	if failOnErrors && hasFailures {
		os.Exit(1)
	}
}

func writeJSON(path string, bundle interface{}, verbose bool) error {
	f, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create JSON: %w", err)
	}
	enc := json.NewEncoder(f)
	enc.SetIndent("", "  ")
	if err := enc.Encode(bundle); err != nil {
		f.Close()
		return fmt.Errorf("write JSON: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close JSON: %w", err)
	}
	return nil
}

func collectJSONLFiles(paths []string) ([]string, error) {
	var files []string
	seen := map[string]bool{}
	for _, p := range paths {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		// Expand simple globs too
		if hasGlob(p) {
			matches, err := filepath.Glob(p)
			if err != nil {
				return nil, fmt.Errorf("invalid glob %q: %w", p, err)
			}
			for _, m := range matches {
				if addJSONL(&files, seen, m) {
					continue
				}
			}
			continue
		}
		info, err := os.Stat(p)
		if err != nil {
			return nil, fmt.Errorf("stat %s: %w", p, err)
		}
		if info.IsDir() {
			err := filepath.Walk(p, func(fp string, fi os.FileInfo, err error) error {
				if err != nil {
					return err
				}
				if !fi.IsDir() && strings.HasSuffix(fp, ".jsonl") {
					addJSONL(&files, seen, fp)
				}
				return nil
			})
			if err != nil {
				return nil, fmt.Errorf("walk %s: %w", p, err)
			}
		} else {
			addJSONL(&files, seen, p)
		}
	}
	return files, nil
}

func addJSONL(files *[]string, seen map[string]bool, path string) bool {
	if !strings.HasSuffix(path, ".jsonl") {
		return false
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		abs = path
	}
	if !seen[abs] {
		*files = append(*files, abs)
		seen[abs] = true
	}
	return true
}

func hasGlob(s string) bool {
	return strings.ContainsAny(s, "*?[")
}

func uniqStrings(xs []string) []string {
	seen := map[string]bool{}
	out := make([]string, 0, len(xs))
	for _, x := range xs {
		if !seen[x] {
			seen[x] = true
			out = append(out, x)
		}
	}
	return out
}


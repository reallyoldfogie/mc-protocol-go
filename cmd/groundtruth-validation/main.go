package main

import (
	"flag"
	"fmt"
	"os"

	data "github.com/reallyoldfogie/mc-protocol-go/data/1.21.5"
	"github.com/reallyoldfogie/mc-protocol-go/internal/packetlogtest"
)

func main() {
	var (
		testFile    string
		verbose     bool
		showSuccess bool
	)

	flag.StringVar(&testFile, "test-file", "", "Path to ground truth test file (JSONL format)")
	flag.BoolVar(&verbose, "verbose", false, "Show detailed output")
	flag.BoolVar(&showSuccess, "show-success", false, "Show successful validations (default: only failures)")

	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: %s -test-file <path>\n\n", os.Args[0])
		fmt.Fprintln(os.Stderr, "Validates Go packet parser against ground truth test cases generated by node-minecraft-protocol.")
		fmt.Fprintln(os.Stderr, "\nOptions:")
		flag.PrintDefaults()
		fmt.Fprintln(os.Stderr, "\nExample:")
		fmt.Fprintln(os.Stderr, "  go run ./cmd/groundtruth-validation -test-file testing/packet-generator/test-packets.jsonl")
	}

	flag.Parse()

	if testFile == "" {
		fmt.Fprintln(os.Stderr, "Error: -test-file is required")
		flag.Usage()
		os.Exit(1)
	}

	// Use 1.21.5 packet manager
	packetMgr := data.NewPackets()

	// Run validation
	results, err := packetlogtest.ValidateGroundTruth(testFile, packetMgr)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}

	// Display results
	successCount := 0
	failCount := 0

	for _, result := range results {
		if result.Success {
			successCount++
			if showSuccess {
				fmt.Printf("✓ %s (%s, ID=%d)\n", result.Description, result.PacketName, result.PacketID)
			}
		} else {
			failCount++
			fmt.Printf("✗ %s (%s, ID=%d)\n", result.Description, result.PacketName, result.PacketID)
			for _, err := range result.Errors {
				fmt.Printf("  - %s\n", err)
			}
		}
	}

	// Summary
	fmt.Printf("\n")
	fmt.Printf("Summary:\n")
	fmt.Printf("  Total:   %d\n", len(results))
	fmt.Printf("  Success: %d (%.1f%%)\n", successCount, float64(successCount)/float64(len(results))*100)
	fmt.Printf("  Failed:  %d (%.1f%%)\n", failCount, float64(failCount)/float64(len(results))*100)

	if failCount > 0 {
		os.Exit(1)
	}
}
